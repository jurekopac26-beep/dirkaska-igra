/* =========================================================================
   REALIZEM 7 — the town tracks (docs/realizem/k7-mestne.md): what the chase camera sees by the road in town, after the sources only
   (OpenStreetMap: building:levels, height, sidewalk, kerb, lit, barrier; never anything made up). A wrapper over the tracks' own
   builders (World.ext.<theme>), loaded after them (index.html), like js/world-aguascalientes.js on js/world-rbring.js: the tracks'
   files are not changed. Nothing here for the 15 tracks of the realism packages (docs/realizem.md), for the race circuits
   (js/world-realizem6.js) or the mountain and open roads (js/world-realizem5.js).
   ========================================================================= */
(function () {
  'use strict';
  if (typeof World === 'undefined' || !World.api || !World.ext) return;

  // ---- the data of each town track (generated by tools/realizem7/build.py from OpenStreetMap; empty until it is filled) ----
  const RZ7 = {};

  for (const id of Object.keys(RZ7)) {
    const base = World.ext[id];
    if (typeof base !== 'function') continue;
    World.ext[id] = (scene, tex, opts) => base(scene, tex, opts);
  }
})();
